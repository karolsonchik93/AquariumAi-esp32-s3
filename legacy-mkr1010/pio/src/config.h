/* ---------------------------------------------------------------------
   3. Пины (распиновка MKR WiFi 1010 — см. WIRING.md)
   --------------------------------------------------------------------- */
#define PIN_RELAY_PUMP       0    // канал 1: помпа
#define PIN_RELAY_AIR        1    // канал 2: компрессор / аэратор
#define PIN_RELAY_FAN        2    // канал 3: вентилятор охлаждения
#define PIN_RELAY_HEAT       3    // канал 4: подогреватель 75 Вт

#define PIN_LED_1            4    // ШИМ: белый канал светильника
#define PIN_LED_2            5    // ШИМ: синий канал светильника
#define PIN_LED_3            10   // ШИМ: третий канал (включается LED_CHANNELS 3)

#define PIN_STATUS_LED       6    // встроенный светодиод (LED_BUILTIN)
#define PIN_ONEWIRE          7    // шина 1-Wire: два DS18B20 + резистор 4.7к на 3V3
#define PIN_FAN_PWM          8    // ШИМ вентилятора (только если FAN_PWM_ENABLE 1)

/* Блок реле с оптопарой — активный НИЗКИЙ уровень (стандарт).
   Если на вашем модуле реле включаются высоким уровнем — поставьте 0,
   но тогда ОБЯЗАТЕЛЬНО проверьте, что при загрузке платы подогреватель
   не включается (см. WIRING.md, раздел «Безопасность»). */
#define RELAY_ACTIVE_LOW     1

/* ---------------------------------------------------------------------
   4. Светильник: число ШИМ-каналов и их параметры по умолчанию
   --------------------------------------------------------------------- */
/* Светильник простой, БЕЗ управления спектром — один канал яркости.
   Если появится многоканальная лампа, поставьте 2 или 3: тогда у каждого
   канала будет своя мощность дня и ночника. */
#define LED_CHANNELS         1    // 1 = обычный светильник, 2..3 = многоканальный
#define LED_PWM_GAMMA        2.2f // гамма-коррекция для человеческого глаза

/* ---------------------------------------------------------------------
   5. Термостат подогревателя (канал реле 4)
   --------------------------------------------------------------------- */
#define DEF_SETPOINT         25.0f   // целевая температура воды, °C
#define DEF_HYST             0.4f    // половина полосы, °C (вкл ниже sp-h, выкл выше sp+h)
#define DEF_MAX_WATER_TEMP   30.0f   // аварийный порог: нагрев выключается
#define MIN_HEATER_ON_MS     (20UL * 1000UL)        // антидребезг: минимум времени работы
#define MIN_HEATER_OFF_MS    (90UL * 1000UL)        // антидребезг: минимум паузы
#define MAX_HEATER_ON_MS     (45UL * 60UL * 1000UL) // аварийный предел непрерывного нагрева
#define HEATER_LOCK_MS       (10UL * 60UL * 1000UL) // блокировка после аварии
#define DEF_HEATER_POWER_W   75.0f   // для оценки расхода электроэнергии

/* ---------------------------------------------------------------------
   6. Вентилятор охлаждения (канал реле 3)
   --------------------------------------------------------------------- */
#define DEF_FAN_ON_TEMP      27.0f   // включать выше этой температуры воды
#define DEF_FAN_HYST         0.5f
#define FAN_PWM_ENABLE       0       // 1 = управлять скоростью вентилятора ШИМ (PIN_FAN_PWM)

/* ---------------------------------------------------------------------
   7. Светильник: расписание по умолчанию (рассвет — день — закат — ночник)
   --------------------------------------------------------------------- */
#define DEF_LIGHT_ON_H       8
#define DEF_LIGHT_ON_M       0
#define DEF_LIGHT_OFF_H      20
#define DEF_LIGHT_OFF_M      0
#define DEF_LIGHT_RAMP_MIN   40      // длительность рассвета и заката, минут
#define DEF_DAY_PCT_1        80      // мощность в режиме «День», %
#define DEF_DAY_PCT_2        60      // (для многоканального светильника)
#define DEF_DAY_PCT_3        0
#define DEF_NIGHT_PCT_1      5       // режим «Ночник»: яркость сразу после заката, %
#define DEF_NIGHT_PCT_2      0       // 0 = ночник выключен
#define DEF_NIGHT_PCT_3      0
/* Время, когда ночник гаснет совсем — дальше светильник выключен до утра.
   Пример: закат в 20:00, ночник до 23:00 → 3 часа слабого света, потом темнота.
   Если поставить время, равное закату, ночник не включается вообще. */
#define DEF_NIGHT_OFF_H      23
#define DEF_NIGHT_OFF_M      0
#define DEF_DAYS_MASK        0x7F    // бит0 = Вс, бит1 = Пн, ... бит6 = Сб (0x7F = каждый день)

/* ---------------------------------------------------------------------
   8. Прочее
   --------------------------------------------------------------------- */
